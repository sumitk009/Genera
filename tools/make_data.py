#!/usr/bin/env python3
"""Regenerates js/data.js from the question tables in tools/data1.py and tools/data2.py.
Run:  python tools/make_data.py     (from the project folder)
Then commit + push; the website updates automatically."""
import os, sys, json, random
from collections import defaultdict
sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
import engine
import data1
from engine import finalize
OUT = os.path.join(os.path.dirname(os.path.abspath(__file__)), "..", "js", "data.js")
random.seed(7)
qs = finalize()
bycat = defaultdict(list)
for q in qs: bycat[q["cat"]].append(q)
for c in bycat: random.shuffle(bycat[c])

NSETS = len(qs) // 100
total = NSETS * 100
# trim extras from largest categories
while sum(len(v) for v in bycat.values()) > total:
    c = max(bycat, key=lambda k: len(bycat[k])); bycat[c].pop()
# deal round-robin so every set is a balanced mix
sets = [[] for _ in range(NSETS)]
i = 0
for c in sorted(bycat, key=lambda k: -len(bycat[k])):
    for q in bycat[c]:
        sets[i % NSETS].append(q); i += 1
for s in sets: random.shuffle(s)

LET = "ABCD"
def place(s):
    pos = [0, 1, 2, 3] * 25
    random.shuffle(pos)
    for q, p in zip(s, pos):
        opts = q["d"][:]
        random.shuffle(opts)
        opts.insert(p, q["a"])
        q["opts"], q["ans"] = opts, p
for s in sets: place(s)
M={('GEO','CITY'):0,('GEO','RIVER'):1,('GEO','STATE'):2,('GEO','COUNTRY'):2,('GEO','CUR'):3,('STA','CITY'):4,('STA','STATE'):5,('STA','ABB'):6,('STA','SPORT'):7,('STA','PER'):8,('HIS','PER'):9,('SCI','PER'):10,('SCI','DIS'):11,('SCI','TYPE'):11,('SCI','HOR'):11,('SCI','UNIT'):12,('SCI','MEAS'):12,('SCI','SYM'):13,('SCI','FORM'):13}
M2={'HIN':14,'ENG':15,'MTH':16,'BIH':17,'SCB':18}
tt=lambda q: M2[q["cat"]] if q["cat"] in M2 else M[(q["cat"],q["tp"])]
pack=lambda q:{"t":tt(q),"e":q["en"],"h":q["hi"],"o":[list(o) for o in q["opts"]],"a":q["ans"]}
data=[[pack(q) for q in s] for s in sets]
NG=len(data)
# ---- Bihar Police pattern sets (originals) ----
engine.QS.clear(); import data2
bq=engine.finalize(); R=random.Random(5)
by={}
for q in bq: by.setdefault(q["cat"],[]).append(q)
for v in by.values(): R.shuffle(v)
gk=[q for q in qs if q["cat"] in("GEO","HIS","STA")]; R.shuffle(gk)
PLAN=[("HIN",15),("ENG",15),("MTH",20),("SCB",14),("BIH",20)]
NB=2
for b in range(NB):
    s=[]
    for c,n in PLAN: s+=by[c][b*n:(b+1)*n]
    s+=gk[b*16:(b+1)*16]
    assert len(s)==100,len(s)
    R.shuffle(s); place(s)
    data.append([pack(q) for q in s])

lines = ["// Auto-generated by tools/make_data.py — you can also edit questions by hand.",
         "// t = topic index (see TP in app.js), e = English, h = Hindi, o = options [[en,hi],..], a = correct option index (0=A)",
         f"const NG={NG}; // number of GK sets; sets after these are Bihar Police mocks", "const SETS=["]
for i, s in enumerate(data):
    lines.append(f"// ---- Set {i+1} ----" if i < NG else f"// ---- Bihar Police Mock {i-NG+1} ----"); lines.append("[")
    lines += [json.dumps(q, ensure_ascii=False, separators=(",", ":")) + "," for q in s]; lines.append("],")
lines.append("];")
open(OUT, "w", encoding="utf-8").write("\n".join(lines) + "\n")
print("Wrote", os.path.normpath(OUT), "-", len(data), "sets")
